"""Generate native Clang feature predicates and capability views from one source."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
AUTHORITY = ROOT / "schemas/objc3-language-capabilities.json"
TABLE = ROOT / "toolchains/llvm/generated/ObjC3Features.def"
VIEW = ROOT / "docs/support/clang_foundation_capabilities.json"
PROFILES = ("compatibility", "strict", "strict-concurrency", "strict-system")


def generated(authority: dict) -> tuple[str, str]:
    if authority.get("schema_version") != 1 or authority.get("compiler_family") != "clang-foundation":
        raise ValueError("Unsupported native language capability authority")
    if set(authority) != {"schema_version", "compiler_family", "language_revision", "extension_abi_revision", "features"}:
        raise ValueError("Unknown or missing capability authority field")
    for key in ("language_revision", "extension_abi_revision"):
        if type(authority[key]) is not int or authority[key] <= 0:
            raise ValueError(f"Invalid {key}")
    names, macros = set(), set()
    lines = ["// Generated by scripts/objc3c_toolchain/generate_features.py.",
             "// Edit schemas/objc3-language-capabilities.json, then regenerate."]
    rows = []
    for feature in authority["features"]:
        if set(feature) != {"name", "macro", "aliases", "state", "qualified_targets"}:
            raise ValueError("Unknown or missing feature field")
        name, macro = feature["name"], feature["macro"]
        if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name in names:
            raise ValueError("Invalid or duplicate feature name")
        names.add(name)
        aliases = feature["aliases"]
        if not isinstance(aliases, list):
            raise ValueError("Feature aliases must be an array")
        for spelling in [macro, *aliases]:
            if not isinstance(spelling, str) or not re.fullmatch(r"[A-Z][A-Z0-9_]*", spelling) or spelling in macros:
                raise ValueError("Invalid or duplicate feature macro")
            macros.add(spelling)
        state = feature["state"]
        if state not in ("implemented", "rejected", "reserved", "internal"):
            raise ValueError("Unknown feature support state")
        targets = feature["qualified_targets"]
        if not isinstance(targets, list) or bool(targets) != (state == "implemented"):
            raise ValueError("Implemented features require qualified targets; other states cannot advertise them")
        predicates, seen_targets = [], set()
        for target in targets:
            if set(target) != {"triple", "runtime", "profile", "evidence"}:
                raise ValueError("Unknown or missing qualified target field")
            triple, runtime, profile = target["triple"], target["runtime"], target["profile"]
            if not all(isinstance(value, str) and value for value in (triple, runtime, profile)) or profile not in PROFILES:
                raise ValueError("Invalid qualified target identity")
            evidence = target["evidence"]
            if not isinstance(evidence, list) or not evidence or any(not isinstance(value, str) or not value for value in evidence):
                raise ValueError("Qualified target requires executable evidence identities")
            identity = (triple, runtime, profile)
            if identity in seen_targets:
                raise ValueError("Duplicate qualified target")
            seen_targets.add(identity)
            predicates.append("(Target.getTriple().str() == " + json.dumps(triple) +
                              " && LangOpts.ObjCRuntime.getAsString() == " + json.dumps(runtime) +
                              f" && LangOpts.ObjC3Profile == {PROFILES.index(profile)})")
        predicate = " || ".join(predicates) if predicates else "false"
        lines.append(f"OBJC3_FEATURE({name}, {macro}, ({predicate}))")
        lines.extend(f"OBJC3_FEATURE_ALIAS({name}, {alias}, {alias.lower()})" for alias in aliases)
        rows.append({**feature, "feature_query": "objc3_" + name,
                     "public_macro": "__OBJC3_FEATURE_" + macro + "__"})
    canonical = json.dumps(authority, sort_keys=True, separators=(",", ":")).encode()
    view = {"schema_version": 1, "authority": "schemas/objc3-language-capabilities.json",
            "authority_sha256": hashlib.sha256(canonical).hexdigest(),
            "compiler_family": authority["compiler_family"],
            "language_revision": authority["language_revision"],
            "extension_abi_revision": authority["extension_abi_revision"], "features": rows}
    return "\n".join(lines) + "\n", json.dumps(view, indent=2) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    table, view = generated(json.loads(AUTHORITY.read_text(encoding="utf-8")))
    for path, contents in ((TABLE, table), (VIEW, view)):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != contents:
                raise SystemExit(f"Stale generated capability view: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents, encoding="utf-8")


if __name__ == "__main__":
    main()
