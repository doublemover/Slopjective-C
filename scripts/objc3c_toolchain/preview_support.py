"""Render the install support table from the published SDK manifest."""

import argparse
import json
from pathlib import Path
import re

from .linux_host import HOSTS
from .release_install import published_archive, published_installs

MANIFEST = 'docs/releases/preview-manifest.json'
TABLE = 'docs/releases/preview-support.md'
REPOSITORY = 'https://github.com/doublemover/Slopjective-C'


def render(manifest: dict) -> str:
    tag = manifest['tag']
    revision = manifest['revision']
    if set(manifest['archives']) != set(HOSTS):
        raise ValueError('published preview must include the complete native Linux host inventory')
    text = [
        '# Linux preview support', '',
        '<!-- Generated by scripts.objc3c_toolchain.preview_support. -->', '',
        f'[Download {tag}]({REPOSITORY}/releases/tag/{tag}) · '
        '[Install and verify the SDK](linux.md)', '',
        f'The preview was built from [`{revision[:8]}`]({REPOSITORY}/commit/{revision}). '
        'The table uses the installed distribution receipts in the '
        '[published manifest](preview-manifest.json).', '',
        '<!-- prettier-ignore -->',
        '| Architecture | Clean install distributions | LLVM base | Extension ABI | glibc minimum | libstdc++ minimum |',
        '| --- | --- | --- | --- | --- | --- |',
    ]
    for host in HOSTS:
        archive = published_archive(manifest, host)
        distributions = []
        for row in published_installs(manifest, host, archive):
            family, version = row['distribution'].split(':', 1)
            distributions.append(f'{family.capitalize()} {version}')
        llvm = re.fullmatch(r'llvmorg-([0-9]+\.[0-9]+\.[0-9]+(?:-rc[0-9]+)?)-([a-f0-9]{12})-'
                            r'([a-f0-9]{12})-[a-f0-9]{8}', archive['source_build_id'])
        if (llvm is None or llvm[2] != archive['upstream_commit'][:12] or
                llvm[3] != archive['patch_digest'][:12]):
            raise ValueError(f'{host} preview archive omitted the exact LLVM base version')
        abi = archive['linux_abi']
        architecture = {'linux-x86_64': 'x86-64', 'linux-aarch64': 'AArch64'}[host]
        text.append(f'| {architecture} | {", ".join(distributions)} | '
                    f'{llvm[1]} | {archive["extension_abi"]} | {abi["glibc_minimum"]} | '
                    f'{abi["libstdcxx_symbol_minimum"]} |')
    claims = manifest['profiles_claimed']
    text.extend([
        '',
        ('Conformance profiles claimed by this release include ' + ', '.join(claims) + '.'
         if claims else 'The preview carries no conformance profile claims.'),
        f'See the [feature catalog for {tag}]({REPOSITORY}/blob/{tag}/schemas/objc3-language-capabilities.json) '
        'for qualified features and compiler modes.',
        '',
    ])
    return '\n'.join(text)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    table = root / TABLE
    try:
        expected = render(json.loads((root / MANIFEST).read_bytes()))
    except (KeyError, TypeError, ValueError) as error:
        parser.error(str(error))
    if options.check:
        if not table.is_file() or table.read_text() != expected:
            parser.error(f'{TABLE} differs from {MANIFEST}')
    else:
        table.write_text(expected)


if __name__ == '__main__':
    main()
